let language = navigator.language?.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
export const currentLanguage = () => language;
export const t = text => language === 'en' ? (english[text] ?? text) : text;
export function translateDOM(root=document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent=t(node.dataset.i18n);
  for (const attribute of ['aria-label','title','placeholder'])
    for (const node of root.querySelectorAll('[data-i18n-'+attribute+']')) node.setAttribute(attribute,t(node.getAttribute('data-i18n-'+attribute)));
  document.documentElement.lang=language;
}
export function setLanguage(value) {
  const next=value === 'zh-CN' ? 'zh-CN' : value === 'en' ? 'en' : language;
  const changed=next!==language; language=next; translateDOM();
  if(changed) dispatchEvent(new Event('tai-language-changed'));
}
const systemDark=matchMedia('(prefers-color-scheme: dark)');
let colorMode='system';
function updateColorMode() {
  document.documentElement.dataset.colorMode =
    colorMode==='system' ? (systemDark.matches?'dark':'light') : colorMode;
}
export function setColorMode(value) {
  if (['light','dark','system'].includes(value)) colorMode=value;
  updateColorMode();
}
